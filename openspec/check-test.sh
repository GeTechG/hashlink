#!/usr/bin/env bash
# Self-test of openspec/check.sh: a clean minimal tree passes, each planted fault fails.
# Runs the CLI the same way check.sh does (OPENSPEC, default `openspec`).
set -uo pipefail
here=$(cd "$(dirname "$0")" && pwd)
pin=$(tr -d '[:space:]' < "$here/cli.pin")
t=$(mktemp -d) || exit 2; trap 'rm -rf "$t"' EXIT
fails=0

make_tree() {  # a clean tree in $t/r
  rm -rf "$t/r"; mkdir -p "$t/r"; cd "$t/r" || exit 2
  git init -q
  mkdir -p openspec/specs/demo openspec/changes/live openspec/changes/archive/2026-01-01-old \
    .claude/skills/openspec-propose .agents/skills/openspec-propose
  echo "$pin" > openspec/cli.pin
  printf 'schema: spec-driven\n' > openspec/config.yaml
  cat > openspec/specs/demo/spec.md <<'EOF'
# demo Specification

## Purpose
A demonstration capability that the self-test of the OpenSpec check validates.

## Requirements

### Requirement: Demo
The demo SHALL work.

#### Scenario: It works
- **WHEN** it runs
- **THEN** it works
EOF
  printf 'schema: spec-driven\ncreated: 2026-01-01\n' > openspec/changes/live/.openspec.yaml
  cat > openspec/changes/live/proposal.md <<'EOF'
## Why
The self-test needs an active change that validates.

## What Changes
- Nothing real.
EOF
  mkdir -p openspec/changes/live/specs/demo
  cat > openspec/changes/live/specs/demo/spec.md <<'EOF'
## ADDED Requirements

### Requirement: Second demo
The demo SHALL work twice.

#### Scenario: Twice
- **WHEN** it runs twice
- **THEN** it works twice
EOF
  printf '## 1. Work\n\n- [x] 1.1 Done\n- [ ] 2.1 [human] Check on a device\n' > openspec/changes/archive/2026-01-01-old/tasks.md
  for s in .claude .agents; do
    printf -- '---\nname: openspec-propose\nmetadata:\n  generatedBy: "%s"\n---\n' "$pin" > $s/skills/openspec-propose/SKILL.md
  done
}

expect() {  # expect <ok|fail> <label>
  local out rc
  out=$(bash "$here/check.sh" 2>&1); rc=$?
  if [[ $1 == ok && $rc != 0 ]] || [[ $1 == fail && $rc == 0 ]]; then
    echo "FAIL: $2 (exit $rc)"; echo "$out" | tail -5; fails=1
  else
    echo "ok: $2"
  fi
}

make_tree; expect ok "clean tree"

make_tree
python3 - <<'EOF'
p='openspec/specs/demo/spec.md'; s=open(p).read()
s=s.replace('The demo SHALL work.', 'The demo SHALL work. ' + 'x' * 520)
open(p,'w').write(s)
EOF
expect fail "requirement longer than 500 characters"

make_tree; sed -i 's/^A demonstration.*/TBD - created by archiving change live. Update Purpose after archive./' openspec/specs/demo/spec.md
expect fail "TBD Purpose"

make_tree; rm openspec/changes/live/.openspec.yaml; expect fail "active change without .openspec.yaml"

make_tree; sed -i 's/generatedBy: .*/generatedBy: "0.0.1"/' .agents/skills/openspec-propose/SKILL.md
expect fail "skill generated by another version"

make_tree; rm -r .claude/skills/openspec-propose .agents/skills/openspec-propose; expect fail "no OpenSpec skills"

make_tree; echo '- [ ] 2.2 Run the tests' >> openspec/changes/archive/2026-01-01-old/tasks.md
expect fail "open agent task in the archive"

make_tree; echo '- [ ] 2.3 Ask for [human] review' >> openspec/changes/archive/2026-01-01-old/tasks.md
expect fail "[human] elsewhere on an open task's line"

make_tree; echo "0.0.1" > openspec/cli.pin; sed -i 's/generatedBy: .*/generatedBy: "0.0.1"/' .{claude,agents}/skills/openspec-propose/SKILL.md
expect fail "CLI version differs from the pin"

exit $fails

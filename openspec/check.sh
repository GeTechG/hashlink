#!/usr/bin/env bash
# Validate this repository's OpenSpec tree with the pinned CLI (openspec/specs/openspec-checks).
# Usage: bash openspec/check.sh   (from anywhere inside the repository)
# OPENSPEC overrides the command that runs the CLI; CI sets it to
#   npm exec --yes --package=@fission-ai/openspec@<pin> -- openspec
set -uo pipefail
root=$(git rev-parse --show-toplevel) || exit 2
cd "$root" || exit 2
export OPENSPEC_TELEMETRY=0
read -r -a cli <<< "${OPENSPEC:-openspec}"
pin=$(tr -d '[:space:]' < openspec/cli.pin)
bad=0
fail() { echo "::error::$*"; bad=1; }

# The CLI is the pinned version.
have=$("${cli[@]}" --version 2>/dev/null | tr -d '[:space:]')
if [[ $have != "$pin" ]]; then
  echo "::error::OpenSpec CLI is '${have:-missing}', openspec/cli.pin says $pin; install it: npm i -g @fission-ai/openspec@$pin"
  exit 1
fi

# Specs and active changes validate strictly.
"${cli[@]}" validate --all --strict --no-interactive || fail "openspec validate --all --strict reports issues (above)"

# No main spec keeps the Purpose placeholder an archive writes.
for f in openspec/specs/*/spec.md; do
  purpose=$(awk '/^## Purpose/{p=1; next} /^## /{p=0} p && NF {print; exit}' "$f")
  [[ $purpose == "TBD - created by archiving change"* ]] && fail "$f: Purpose is the TBD placeholder"
done

# Every active change was created by `openspec new change`.
for d in openspec/changes/*/; do
  [[ $d == openspec/changes/archive/ ]] && continue
  [[ -f $d.openspec.yaml ]] || fail "${d%/}: no .openspec.yaml (create changes with 'openspec new change')"
done

# Skills were generated by the pinned CLI.
skills=0
for f in .claude/skills/openspec-*/SKILL.md .agents/skills/openspec-*/SKILL.md; do
  [[ -f $f ]] || continue
  skills=$((skills + 1))
  gen=$(sed -n 's/^[[:space:]]*generatedBy:[[:space:]]*"\{0,1\}\([^"]*\)"\{0,1\}[[:space:]]*$/\1/p' "$f" | head -1)
  [[ $gen == "$pin" ]] || fail "$f: generatedBy '${gen:-none}', openspec/cli.pin says $pin; run 'openspec update'"
done
(( skills > 0 )) || fail "no OpenSpec skills under .claude/skills or .agents/skills"

# An archived change leaves no open task except one marked [human] right after its number.
while IFS= read -r hit; do
  line=${hit#*:*:}
  [[ $line =~ ^[[:space:]]*-\ \[\ \]\ +[0-9]+(\.[0-9]+)*\.?\ +\[human\] ]] && continue
  fail "${hit%%:*}:$(cut -d: -f2 <<< "$hit"): open task in an archived change: ${line#"${line%%[![:space:]]*}"}"
done < <(grep -Hn '^[[:space:]]*- \[ \]' openspec/changes/archive/*/tasks.md 2>/dev/null)

(( bad )) || echo "OpenSpec $pin: ok"
exit $bad
